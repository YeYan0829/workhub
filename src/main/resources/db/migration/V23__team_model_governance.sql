-- Deployment ledgers and all old run/call foreign keys remain legacy, unchanged.
CREATE TABLE team_model_connection (
 workspace_id BINARY(16) PRIMARY KEY,
 version BIGINT NOT NULL,
 provider VARCHAR(16) NOT NULL,
 default_model VARCHAR(80) NOT NULL,
 allowed_models JSON NOT NULL,
 key_cipher TEXT NOT NULL,
 enabled BOOLEAN NOT NULL,
 request_rate DOUBLE NOT NULL,
 request_burst INT NOT NULL,
 updated_by BINARY(16) NOT NULL,
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(workspace_id) REFERENCES workspace(id),
 FOREIGN KEY(updated_by) REFERENCES app_user(id),
 CHECK(version>0 AND request_rate>=0.001 AND request_rate<=10000 AND request_burst BETWEEN 1 AND 10000)
);
CREATE TABLE team_model_budget (
 workspace_id BINARY(16) PRIMARY KEY,
 currency CHAR(3) NOT NULL,
 limit_nanos BIGINT NOT NULL,
 version BIGINT NOT NULL,
 updated_by BINARY(16) NOT NULL,
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(workspace_id) REFERENCES workspace(id),
 FOREIGN KEY(updated_by) REFERENCES app_user(id),
 CHECK(limit_nanos BETWEEN 0 AND 1000000000000000 AND currency IN ('USD','CNY'))
);
CREATE TABLE team_model_period (
 workspace_id BINARY(16) NOT NULL,
 period_start DATE NOT NULL,
 currency CHAR(3) NOT NULL,
 limit_nanos BIGINT NOT NULL,
 settled_nanos BIGINT NOT NULL DEFAULT 0,
 pending_nanos BIGINT NOT NULL DEFAULT 0,
 PRIMARY KEY(workspace_id,period_start),
 FOREIGN KEY(workspace_id) REFERENCES team_model_budget(workspace_id),
 CHECK(settled_nanos>=0 AND pending_nanos>=0 AND settled_nanos+pending_nanos<=limit_nanos)
);
CREATE TABLE project_model_policy (
 project_id BINARY(16) PRIMARY KEY,
 model VARCHAR(80),
 max_calls INT NOT NULL,
 max_cost_nanos BIGINT NOT NULL,
 max_millis INT NOT NULL,
 version BIGINT NOT NULL,
 updated_by BINARY(16) NOT NULL,
 FOREIGN KEY(project_id) REFERENCES project(id),
 FOREIGN KEY(updated_by) REFERENCES app_user(id),
 CHECK(max_calls BETWEEN 1 AND 20 AND max_cost_nanos BETWEEN 1 AND 1000000000000 AND max_millis BETWEEN 1000 AND 300000)
);
CREATE TABLE team_model_run (
 run_id BINARY(16) PRIMARY KEY,
 workspace_id BINARY(16) NOT NULL,
 project_id BINARY(16) NOT NULL,
 connection_version BIGINT NOT NULL,
 policy_version BIGINT NOT NULL,
 model VARCHAR(80) NOT NULL,
 currency CHAR(3) NOT NULL,
 price_version VARCHAR(40) NOT NULL,
 input_price BIGINT NOT NULL,
 output_price BIGINT NOT NULL,
 max_calls INT NOT NULL,
 max_cost_nanos BIGINT NOT NULL,
 max_millis INT NOT NULL,
 call_count INT NOT NULL DEFAULT 0,
 occupied_nanos BIGINT NOT NULL DEFAULT 0,
 trigger_source VARCHAR(24) NOT NULL,
 FOREIGN KEY(run_id) REFERENCES agent_run(id),
 FOREIGN KEY(workspace_id) REFERENCES team_model_connection(workspace_id),
 FOREIGN KEY(project_id) REFERENCES project(id),
 CHECK(call_count BETWEEN 0 AND max_calls AND occupied_nanos BETWEEN 0 AND max_cost_nanos)
);
CREATE TABLE team_model_call (
 id BINARY(16) PRIMARY KEY,
 run_id BINARY(16) NOT NULL,
 attempt_token BINARY(16) NOT NULL,
 workspace_id BINARY(16) NOT NULL,
 project_id BINARY(16) NOT NULL,
 period_start DATE NOT NULL,
 connection_version BIGINT NOT NULL,
 model VARCHAR(80) NOT NULL,
 currency CHAR(3) NOT NULL,
 price_version VARCHAR(40) NOT NULL,
 input_price BIGINT NOT NULL,
 output_price BIGINT NOT NULL,
 input_token_bound BIGINT NOT NULL,
 output_token_bound BIGINT NOT NULL,
 reserved_nanos BIGINT NOT NULL,
 input_tokens BIGINT,
 output_tokens BIGINT,
 estimated_nanos BIGINT,
 state VARCHAR(16) NOT NULL DEFAULT 'RESERVED',
 purpose VARCHAR(16) NOT NULL,
 elapsed_millis BIGINT,
 error_code VARCHAR(80),
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(run_id) REFERENCES team_model_run(run_id),
 FOREIGN KEY(workspace_id,period_start) REFERENCES team_model_period(workspace_id,period_start),
 FOREIGN KEY(project_id) REFERENCES project(id),
 INDEX(workspace_id,period_start,project_id,id),
 INDEX(run_id,purpose),
 CHECK(state IN ('RESERVED','COMPLETE','UNKNOWN'))
);
